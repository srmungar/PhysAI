#!/usr/bin/env python3
"""Generate the `mysubbashirt` soft-cloth model for Gazebo Harmonic (gz-sim 8).

Gazebo Harmonic has no native deformable/cloth body, so the cloth is approximated
with a mass-spring patch model: a T-shirt shaped grid of thin, light rigid patches
connected by universal joints with spring stiffness and damping. Each joint lets
neighbouring patches fold (bend out of plane) and twist, which gives a soft,
draping behaviour.

DART (Gazebo's default physics engine) does not support closed kinematic loops,
so the patches are connected as a spanning tree: a vertical "spine" down the
centre of the shirt, with horizontal branches out to each side (and sleeves).

Usage:
    python3 scripts/generate_mysubbashirt.py            # writes models/mysubbashirt/model.sdf
    python3 scripts/generate_mysubbashirt.py --cell 0.04 --stiffness 0.002
"""

import argparse
import os
from collections import deque

MODEL_NAME = "mysubbashirt"


def shirt_mask(body_w, body_h, sleeve_w, sleeve_h, neck_w):
    """Return the set of (col, row) cells that make up a flat T-shirt.

    Row 0 is the shoulder line (top of the shirt); rows increase towards the hem.
    """
    total_w = body_w + 2 * sleeve_w
    cells = set()
    for row in range(body_h):
        for col in range(total_w):
            in_body = sleeve_w <= col < sleeve_w + body_w
            in_sleeve = row < sleeve_h
            if in_body or in_sleeve:
                cells.add((col, row))
    # Neckline cut-out in the top row (centred).
    neck_start = sleeve_w + (body_w - neck_w) // 2
    for col in range(neck_start, neck_start + neck_w):
        cells.discard((col, 0))
    return cells, total_w


def spanning_tree(cells, spine_col):
    """Comb-shaped spanning tree: vertical spine, horizontal branches, BFS fallback.

    Returns (root, parent_of) where parent_of[child] = parent cell.
    """
    spine = sorted(r for (c, r) in cells if c == spine_col)
    root = (spine_col, spine[0])
    parent_of = {}
    in_tree = {root}

    # 1) spine (vertical chain down the centre column)
    for prev, cur in zip(spine, spine[1:]):
        parent_of[(spine_col, cur)] = (spine_col, prev)
        in_tree.add((spine_col, cur))

    # 2) horizontal branches out from each spine cell
    for r in spine:
        for step in (-1, 1):
            prev = (spine_col, r)
            c = spine_col + step
            while (c, r) in cells:
                parent_of[(c, r)] = prev
                in_tree.add((c, r))
                prev = (c, r)
                c += step

    # 3) anything left (e.g. shoulders beside the neckline) via BFS
    queue = deque(sorted(in_tree))
    while queue:
        cur = queue.popleft()
        c, r = cur
        for nb in ((c, r + 1), (c, r - 1), (c - 1, r), (c + 1, r)):
            if nb in cells and nb not in in_tree:
                parent_of[nb] = cur
                in_tree.add(nb)
                queue.append(nb)

    missing = cells - in_tree
    if missing:
        raise RuntimeError(f"cells not connected to the cloth: {sorted(missing)}")
    return root, parent_of


def link_name(cell):
    return f"patch_{cell[0]}_{cell[1]}"


def build_sdf(a):
    cells, total_w = shirt_mask(a.body_w, a.body_h, a.sleeve_w, a.sleeve_h, a.neck_w)
    # Spine is just off-centre so it does not fall inside the neckline cut-out.
    spine_col = a.sleeve_w + (a.body_w - a.neck_w) // 2 - 1
    root, parent_of = spanning_tree(cells, spine_col)

    s = a.cell
    t = a.thickness
    m = a.mass / len(cells)
    ixx = m / 12.0 * (s * s + t * t)
    izz = m / 12.0 * (2 * s * s)
    coll = s * 0.92  # slightly smaller collision box so neighbours never overlap

    # Centre the shirt on the model origin; +Y points to the collar.
    x0 = (total_w - 1) * s / 2.0
    y0 = (a.body_h - 1) * s / 2.0

    def pos(cell):
        c, r = cell
        return (c * s - x0, y0 - r * s)

    out = []
    w = out.append
    w('<?xml version="1.0"?>')
    w("<!-- AUTO-GENERATED by scripts/generate_mysubbashirt.py - edit the script, not this file. -->")
    w('<sdf version="1.10">')
    w(f'  <model name="{MODEL_NAME}">')
    w("    <static>false</static>")
    w("    <self_collide>false</self_collide>")
    w(f"    <!-- {len(cells)} patches, {s} m cell, total mass {a.mass} kg -->")

    for cell in sorted(cells, key=lambda c: (c[1], c[0])):
        x, y = pos(cell)
        w(f'    <link name="{link_name(cell)}">')
        w(f"      <pose>{x:.4f} {y:.4f} 0 0 0 0</pose>")
        w("      <inertial>")
        w(f"        <mass>{m:.6f}</mass>")
        w(f"        <inertia><ixx>{ixx:.4e}</ixx><iyy>{ixx:.4e}</iyy><izz>{izz:.4e}</izz>"
          "<ixy>0</ixy><ixz>0</ixz><iyz>0</iyz></inertia>")
        w("      </inertial>")
        w('      <collision name="collision">')
        w(f"        <geometry><box><size>{coll:.4f} {coll:.4f} {t:.4f}</size></box></geometry>")
        w("        <surface>")
        w("          <friction><ode><mu>1.0</mu><mu2>1.0</mu2></ode></friction>")
        w("          <bounce><restitution_coefficient>0</restitution_coefficient></bounce>")
        w("          <contact><ode><kp>1e4</kp><kd>10</kd><max_vel>0.1</max_vel>"
          "<min_depth>0.001</min_depth></ode></contact>")
        w("        </surface>")
        w("      </collision>")
        w('      <visual name="visual">')
        w(f"        <geometry><box><size>{s:.4f} {s:.4f} {t:.4f}</size></box></geometry>")
        w("        <material>")
        w(f"          <ambient>{a.color}</ambient>")
        w(f"          <diffuse>{a.color}</diffuse>")
        w("          <specular>0.05 0.05 0.05 1</specular>")
        w("        </material>")
        w("      </visual>")
        w("    </link>")

    for child, parent in sorted(parent_of.items(), key=lambda kv: (kv[0][1], kv[0][0])):
        dc, dr = child[0] - parent[0], child[1] - parent[1]
        # Direction from parent to child in model XY (rows grow towards -Y).
        dx, dy = dc, -dr
        # Joint sits on the shared edge, expressed relative to the child link.
        jx, jy = -dx * s / 2.0, -dy * s / 2.0
        # axis 1: fold (in-plane, perpendicular to the connection)
        # axis 2: twist (along the connection)
        fold = f"{abs(dy)} {abs(dx)} 0"
        twist = f"{abs(dx)} {abs(dy)} 0"
        w(f'    <joint name="j_{link_name(child)}" type="universal">')
        w(f"      <pose>{jx:.4f} {jy:.4f} 0 0 0 0</pose>")
        w(f"      <parent>{link_name(parent)}</parent>")
        w(f"      <child>{link_name(child)}</child>")
        for tag, xyz, k in (("axis", fold, a.stiffness), ("axis2", twist, a.stiffness * a.twist_ratio)):
            w(f"      <{tag}>")
            w(f"        <xyz>{xyz}</xyz>")
            w(f"        <limit><lower>{-a.max_bend:.3f}</lower><upper>{a.max_bend:.3f}</upper></limit>")
            w(f"        <dynamics><damping>{a.damping}</damping><friction>0</friction>"
              f"<spring_reference>0</spring_reference><spring_stiffness>{k}</spring_stiffness></dynamics>")
            w(f"      </{tag}>")
        w("    </joint>")

    w("  </model>")
    w("</sdf>")
    return "\n".join(out) + "\n", len(cells)


def main():
    here = os.path.dirname(os.path.abspath(__file__))
    default_out = os.path.join(here, "..", "models", MODEL_NAME, "model.sdf")

    p = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    p.add_argument("--cell", type=float, default=0.05, help="patch edge length [m]")
    p.add_argument("--thickness", type=float, default=0.004, help="patch thickness [m]")
    p.add_argument("--body-w", type=int, default=10, help="body width in cells")
    p.add_argument("--body-h", type=int, default=13, help="body height in cells")
    p.add_argument("--sleeve-w", type=int, default=3, help="sleeve length in cells (each side)")
    p.add_argument("--sleeve-h", type=int, default=4, help="sleeve width in cells")
    p.add_argument("--neck-w", type=int, default=2, help="neck cut-out width in cells")
    p.add_argument("--mass", type=float, default=0.3, help="total cloth mass [kg]")
    p.add_argument("--stiffness", type=float, default=0.001,
                   help="bending spring stiffness [Nm/rad]; lower = softer")
    p.add_argument("--twist-ratio", type=float, default=2.0, help="twist stiffness / bend stiffness")
    p.add_argument("--damping", type=float, default=0.0015, help="joint damping [Nms/rad]")
    p.add_argument("--max-bend", type=float, default=2.6, help="joint limit [rad]")
    p.add_argument("--color", default="0.15 0.35 0.75 1", help="RGBA colour")
    p.add_argument("-o", "--output", default=default_out)
    a = p.parse_args()

    sdf, n = build_sdf(a)
    os.makedirs(os.path.dirname(os.path.abspath(a.output)), exist_ok=True)
    with open(a.output, "w") as f:
        f.write(sdf)
    print(f"wrote {os.path.normpath(a.output)} ({n} patches)")


if __name__ == "__main__":
    main()
